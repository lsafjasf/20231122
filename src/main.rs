//! plc-eval: offline packet-loss concealment evaluation CLI.

use std::path::PathBuf;

use anyhow::{Context, Result};
use clap::{Parser, Subcommand};

use plc_eval::eval;
use plc_eval::loss::{LossKind, LossManifest};
use plc_eval::signal::Synth;
use plc_eval::wav::{Wav, WavSpec};
use plc_eval::Strategy;

const RATE: u32 = 16_000;

#[derive(Parser)]
#[command(
    name = "plc-eval",
    about = "Offline PLC evaluation: silence / repeat / interpolate"
)]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Generate clean + degraded sample WAVs for the three loss types.
    GenSamples {
        /// Output directory.
        #[arg(short, long, default_value = "samples")]
        out: PathBuf,
        /// Duration of each sample in seconds.
        #[arg(short, long, default_value_t = 5.9)]
        duration: f32,
    },
    /// Evaluate all strategies on a degraded file and print the report.
    Analyze {
        /// Clean (original) WAV.
        #[arg(long)]
        clean: PathBuf,
        /// Degraded (with packet loss) WAV.
        #[arg(long)]
        degraded: PathBuf,
        /// Loss manifest produced by `gen-samples`.
        #[arg(long)]
        manifest: PathBuf,
        /// Also write the best-strategy recovered WAV here.
        #[arg(long)]
        recovered: Option<PathBuf>,
        /// Print every strategy's score per gap, not just the winner.
        #[arg(long)]
        scores: bool,
    },
    /// Recover a degraded file with one fixed strategy (for listening).
    Recover {
        #[arg(long)]
        degraded: PathBuf,
        #[arg(long)]
        manifest: PathBuf,
        #[arg(long, value_parser = clap::value_parser!(Strategy))]
        strategy: Strategy,
        #[arg(short, long)]
        out: PathBuf,
    },
    /// Run the three sample types and check strategy choice + reduction.
    Check {
        /// Directory with samples generated by `gen-samples`.
        #[arg(short, long, default_value = "samples")]
        dir: PathBuf,
        /// Minimum mean reduction vs silence (dB) required to pass.
        #[arg(long, default_value_t = 3.0)]
        min_reduction: f32,
    },
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.cmd {
        Cmd::GenSamples { out, duration } => gen_samples(&out, duration),
        Cmd::Analyze {
            clean,
            degraded,
            manifest,
            recovered,
            scores,
        } => analyze(&clean, &degraded, &manifest, recovered, scores),
        Cmd::Recover {
            degraded,
            manifest,
            strategy,
            out,
        } => {
            let degraded = Wav::read(&degraded)?;
            let text = std::fs::read_to_string(&manifest)
                .with_context(|| format!("read {}", manifest.display()))?;
            let manifest = LossManifest::from_text(&text)?;
            let wav = eval::recover_with(&degraded, &manifest, strategy);
            wav.write(&out)?;
            println!("wrote {} (strategy={strategy})", out.display());
            Ok(())
        }
        Cmd::Check { dir, min_reduction } => check(&dir, min_reduction),
    }
}

fn gen_samples(out: &std::path::Path, duration: f32) -> Result<()> {
    std::fs::create_dir_all(out)?;
    // Two talkers (near end 120 Hz, far end 210 Hz) -> stereo recording.
    let mut synth_l = Synth::new(0x5EED_1234);
    let mut synth_r = Synth::new(0x5EED_9876);
    let left = synth_l.voice(duration, RATE, 120.0);
    let right = synth_r.voice(duration, RATE, 210.0);
    let mut interleaved = Vec::with_capacity(left.len() * 2);
    for i in 0..left.len() {
        interleaved.push(left[i]);
        interleaved.push(right[i]);
    }
    let clean = Wav {
        spec: WavSpec {
            sample_rate: RATE,
            channels: 2,
        },
        samples: interleaved,
    };
    clean.write(&out.join("clean.wav"))?;

    let total_frames = (clean.frames() * 1000) / (RATE as usize * plc_eval::FRAME_MS);
    for kind in LossKind::ALL {
        // One-sided loss hits channel 1 (far end); others hit channel 0.
        let channel = if kind == LossKind::OneSided { 1 } else { 0 };
        let manifest = LossManifest::generate(kind, total_frames, channel);
        let degraded = manifest.degrade(&clean);
        let stem = kind.label();
        degraded.write(&out.join(format!("{stem}.wav")))?;
        std::fs::write(out.join(format!("{stem}.manifest.txt")), manifest.to_text())?;
        println!(
            "generated {stem}: {} gaps, {} lost frames total",
            manifest.gaps.len(),
            manifest.gaps.iter().map(|g| g.frames).sum::<usize>()
        );
    }
    Ok(())
}

fn analyze(
    clean: &std::path::Path,
    degraded: &std::path::Path,
    manifest: &std::path::Path,
    recovered: Option<PathBuf>,
    scores: bool,
) -> Result<()> {
    let clean = Wav::read(clean)?;
    let degraded = Wav::read(degraded)?;
    let text = std::fs::read_to_string(manifest)
        .with_context(|| format!("read {}", manifest.display()))?;
    let manifest = LossManifest::from_text(&text)?;
    let reports = eval::evaluate(&clean, &degraded, &manifest);
    if scores {
        print!("{}", eval::format_all_scores(&reports));
    } else {
        print!("{}", eval::format_reports(&reports));
    }
    println!();
    print!("{}", eval::summarize(&reports));
    if let Some(path) = recovered {
        let wav = eval::recover(&degraded, &manifest, &reports);
        wav.write(&path)?;
        println!("wrote {}", path.display());
    }
    Ok(())
}

fn check(dir: &std::path::Path, min_reduction: f32) -> Result<()> {
    let clean = Wav::read(&dir.join("clean.wav"))?;
    let mut failures = Vec::new();
    for kind in LossKind::ALL {
        let stem = kind.label();
        let degraded = Wav::read(&dir.join(format!("{stem}.wav")))?;
        let text = std::fs::read_to_string(dir.join(format!("{stem}.manifest.txt")))?;
        let manifest = LossManifest::from_text(&text)?;
        let reports = eval::evaluate(&clean, &degraded, &manifest);
        // Only voiced gaps (non-trivial original energy) are meaningful
        // for strategy selection; in pauses every strategy ties.
        let voiced: Vec<&eval::GapReport> = reports.iter().filter(|r| r.ref_rms > 0.02).collect();
        let mean_red =
            voiced.iter().map(|r| r.reduction_db).sum::<f32>() / voiced.len().max(1) as f32;
        // Expected winning strategy per loss type.
        let expected = match kind {
            LossKind::Isolated => Strategy::Interpolate,
            LossKind::Burst => Strategy::Interpolate,
            LossKind::OneSided => Strategy::Interpolate,
        };
        let wins = voiced.iter().filter(|r| r.best == expected).count();
        let win_rate = wins as f32 / voiced.len().max(1) as f32;
        println!(
            "[{stem}] expected={} win_rate={:.0}% ({} voiced gaps) mean_reduction={:.2} dB",
            expected,
            win_rate * 100.0,
            voiced.len(),
            mean_red
        );
        if win_rate < 0.5 {
            failures.push(format!(
                "{stem}: expected strategy {expected} won only {wins}/{} voiced gaps",
                voiced.len()
            ));
        }
        if mean_red < min_reduction {
            failures.push(format!(
                "{stem}: mean reduction {mean_red:.2} dB < required {min_reduction:.2} dB"
            ));
        }
        // Burst-specific: the trailing dropout gap has no future context,
        // so backward-looking repeat-last-frame must win there.
        if kind == LossKind::Burst {
            if let Some(last) = reports.last() {
                println!(
                    "[{stem}] trailing gap {} -> {} (expected repeat)",
                    last.gap_index, last.best
                );
                if last.best != Strategy::RepeatLastFrame {
                    failures.push(format!(
                        "{stem}: trailing gap chose {} instead of repeat",
                        last.best
                    ));
                }
            }
        }
    }
    if failures.is_empty() {
        println!("CHECK PASS");
        Ok(())
    } else {
        for f in &failures {
            eprintln!("FAIL: {f}");
        }
        anyhow::bail!("{} check(s) failed", failures.len())
    }
}
